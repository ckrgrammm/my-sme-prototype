export function t(lang, key, ...args) {
  const entry = UI[lang]?.[key] ?? UI.zh[key];
  return typeof entry === 'function' ? entry(...args) : entry;
}

/** Pick the current-language string out of a {zh, en} bilingual field.
 *  Plain strings (proper nouns, codes, routes) pass through unchanged. */
export function pick(lang, val) {
  if (val && typeof val === 'object' && ('zh' in val || 'en' in val)) {
    return val[lang] ?? val.zh ?? val.en ?? '';
  }
  return val;
}
